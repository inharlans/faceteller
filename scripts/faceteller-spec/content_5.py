features=schema['features']
def feature_rows(parts):
 rows=[]
 for k,v in features.items():
  if v['part'] not in parts:continue
  method={'landmark':'좌표 비율·각도','visual':'부위 영상 분류','multiview':'다중시점 깊이'}[v['source']]
  note='채택 전 검수·평가'
  if v['source']=='multiview':note='정면 서비스 기본 제외'
  if k in ['eye_depth','cheekbone']:note='깊이 실측 아님; 재검증'
  rows.append((k+'\n'+v['ko'],' / '.join(v['classes_ko']),method+'\n'+note))
 return rows
